function el(tag, cls, text){
  var n = document.createElement(tag);
  if (cls) n.className = cls;
  if (text !== undefined && text !== null) n.textContent = String(text);
  return n;
}

function toast(message, kind){
  var box = document.getElementById('toasts');
  var t = el('div', 'toast ' + (kind || ''));
  t.textContent = message;
  box.appendChild(t);
  setTimeout(function(){
    t.style.opacity = '0';
    t.style.transition = 'opacity .4s';
    setTimeout(function(){ if (t.parentNode) t.parentNode.removeChild(t); }, 450);
  }, kind === 'err' ? 7000 : 4500);
}

function safeUrl(u){
  if (typeof u !== 'string' || u === '') return null;
  if (/^(https?:|magnet:)/i.test(u)) return u;
  return null;
}

function formatSize(n){
  if (n === null || n === undefined || isNaN(Number(n))) return '—';
  var units = ['B','KB','MB','GB','TB','PB'];
  var x = Number(n), i = 0;
  while (x >= 1024 && i < units.length - 1){ x /= 1024; i++; }
  if (i === 0) return x + ' B';
  return (x >= 100 ? x.toFixed(0) : x.toFixed(1)) + ' ' + units[i];
}

function ageMinutes(r){
  if (r.publishDate){
    var t = Date.parse(r.publishDate);
    if (!isNaN(t)) return Math.max(0, (Date.now() - t) / 60000);
  }
  if (r.ageMinutes !== undefined && r.ageMinutes !== null && !isNaN(Number(r.ageMinutes))) return Number(r.ageMinutes);
  if (r.ageHours !== undefined && r.ageHours !== null && !isNaN(Number(r.ageHours))) return Number(r.ageHours) * 60;
  if (r.age !== undefined && r.age !== null && !isNaN(Number(r.age))) return Number(r.age) * 1440;
  return null;
}

function formatAge(r){
  var m = ageMinutes(r);
  if (m === null) return '—';
  if (m < 60) return Math.max(1, Math.floor(m)) + 'm';
  if (m < 2880) return Math.floor(m / 60) + 'h';
  return Math.floor(m / 1440) + 'd';
}

function categoryText(r){
  var cats = r.categories;
  if (!cats || !cats.length) return '—';
  var names = [];
  for (var i = 0; i < cats.length; i++){
    var c = cats[i];
    if (c && typeof c === 'object') names.push(String(c.name || c.id || ''));
    else names.push(String(c));
  }
  return names.filter(Boolean).join(', ') || '—';
}

function renderVariants(list){
  variantsEl.innerHTML = '';
  if (!list || !list.length) return;
  variantsEl.appendChild(el('span', 'vlabel', list.length > 1 ? 'searched:' : 'searched:'));
  for (var i = 0; i < list.length; i++){
    variantsEl.appendChild(el('span', 'chip', list[i]));
  }
}

function renderErrors(list){
  errorsEl.innerHTML = '';
  if (!list || !list.length) return;
  for (var i = 0; i < list.length; i++){
    var e = list[i];
    var d = el('div', 'err');
    d.textContent = (e.variant ? 'Variant "' + e.variant + '": ' : '') + (e.error || 'Unknown error');
    errorsEl.appendChild(d);
  }
}

function sortValue(r, key){
  switch (key){
    case 'title': return String(r.title || '').toLowerCase();
    case 'age': { var m = ageMinutes(r); return m === null ? Number.MAX_SAFE_INTEGER : m; }
    case 'size': return Number(r.size) || 0;
    case 'seeders': return String(r.protocol || '').toLowerCase() === 'usenet' ? (Number(r.grabs) || 0) : (Number(r.seeders) || 0);
    case 'indexer': return String(r.indexer || '').toLowerCase();
  }
  return 0;
}

function renderRows(){
  rowsEl.innerHTML = '';
  var arr = state.results.slice();
  arr.sort(function(a, b){
    var va = sortValue(a, state.sortKey), vb = sortValue(b, state.sortKey);
    var c = 0;
    if (typeof va === 'string' && typeof vb === 'string') c = va < vb ? -1 : (va > vb ? 1 : 0);
    else c = va - vb;
    if (c === 0) c = String(a.title || '') < String(b.title || '') ? -1 : (String(a.title || '') > String(b.title || '') ? 1 : 0);
    return state.sortDir === 'asc' ? c : -c;
  });

  if (!arr.length){
    var tr = el('tr');
    var td = el('td', 'empty', state.searched ? 'No results.' : 'Search something to get started.');
    td.colSpan = 9;
    tr.appendChild(td);
    rowsEl.appendChild(tr);
    return;
  }

  for (var i = 0; i < arr.length; i++){
    var r = arr[i];
    var tr = el('tr');

    var tdTitle = el('td', 'title');
    var infoUrl = safeUrl(r.infoUrl);
    if (infoUrl){
      var a = el('a', null, String(r.title || '(untitled)'));
      a.href = infoUrl;
      a.target = '_blank';
      a.rel = 'noopener noreferrer';
      tdTitle.appendChild(a);
    } else {
      tdTitle.appendChild(el('span', null, String(r.title || '(untitled)')));
    }
    tr.appendChild(tdTitle);

    tr.appendChild(el('td', 'cat', categoryText(r)));
    tr.appendChild(el('td', 'num', formatAge(r)));
    tr.appendChild(el('td', 'num', formatSize(r.size)));

    var seed = '—';
    if (String(r.protocol || '').toLowerCase() === 'usenet'){
      if (r.grabs !== undefined && r.grabs !== null) seed = String(r.grabs);
    } else if (r.seeders !== undefined && r.seeders !== null){
      seed = String(r.seeders);
      if (r.leechers !== undefined && r.leechers !== null) seed += ' / ' + String(r.leechers);
    }
    tr.appendChild(el('td', 'num', seed));

    tr.appendChild(el('td', null, String(r.indexer || '—')));

    var tdProto = el('td');
    var proto = String(r.protocol || '').toLowerCase();
    var badge = el('span', 'badge ' + proto, proto || '?');
    tdProto.appendChild(badge);
    tr.appendChild(tdProto);

    var tdLinks = el('td', 'links');
    var commentUrl = safeUrl(r.commentUrl);
    var magnetUrl = safeUrl(r.magnetUrl);
    if (commentUrl){
      var ac = el('a', null, 'comment');
      ac.href = commentUrl; ac.target = '_blank'; ac.rel = 'noopener noreferrer';
      tdLinks.appendChild(ac);
    }
    if (magnetUrl){
      var am = el('a', null, 'magnet');
      am.href = magnetUrl;
      tdLinks.appendChild(am);
    }
    if (!commentUrl && !magnetUrl) tdLinks.appendChild(el('span', null, '—'));
    tr.appendChild(tdLinks);

    var tdGrab = el('td');
    var grabBtn = el('button', 'primary', 'Grab');
    grabBtn.type = 'button';
    (function(row, btn){
      btn.addEventListener('click', function(){ grab(row, btn); });
    })(r, grabBtn);
    tdGrab.appendChild(grabBtn);
    tr.appendChild(tdGrab);

    rowsEl.appendChild(tr);
  }

  var heads = document.querySelectorAll('th.sortable');
  for (var h = 0; h < heads.length; h++){
    var th = heads[h];
    var key = th.getAttribute('data-sort');
    var base = th.textContent.replace(/[▲▼]\s*$/, '').trim();
    th.textContent = base;
    if (key === state.sortKey){
      th.appendChild(document.createTextNode(' ' + (state.sortDir === 'asc' ? '▲' : '▼')));
    }
  }
}

function setBusy(busy){
  goBtn.disabled = busy;
  cancelBtn.classList.toggle('hidden', !busy);
  if (busy){
    metaEl.innerHTML = '';
    metaEl.appendChild(el('span', 'spin'));
    metaEl.appendChild(el('span', null, 'Searching…'));
  }
}

function updateIdHint(){
  var hasId = /\{[^}]+\}/.test(qEl.value);
  idHintEl.classList.toggle('hidden', !(hasId && typeEl.value === 'search'));
}

function currentQuery(){ return qEl.value.trim(); }

function runSearch(){
  var query = currentQuery();
  if (!query){
    state.results = [];
    state.searched = false;
    renderRows();
    renderVariants([]);
    renderErrors([]);
    metaEl.textContent = '';
    return;
  }
  if (controller) controller.abort();
  controller = new AbortController();
  var signal = controller.signal;

  setBusy(true);

  var params = new URLSearchParams();
  params.set('action', 'search');
  params.set('query', query);
  params.set('type', typeEl.value);
  params.set('limit', String(limitEl.value || window.PURSUARR.defaultLimit));
  var ids = selectedIndexerIds();
  if (ids.length) params.set('indexerIds', ids.join(','));
  if (categoryEl.value) params.set('categories', categoryEl.value);

  fetch('?' + params.toString(), {signal: signal})
    .then(function(res){ return res.json(); })
    .then(function(data){
      if (signal.aborted) return;
      state.results = Array.isArray(data.results) ? data.results : [];
      state.searched = true;
      renderVariants(data.variantsUsed || []);
      renderErrors(data.errors || []);
      renderRows();
      metaEl.textContent = state.results.length + ' result' + (state.results.length === 1 ? '' : 's')
        + (data.errors && data.errors.length ? ' · ' + data.errors.length + ' variant error' + (data.errors.length === 1 ? '' : 's') : '');
    })
    .catch(function(err){
      if (err && err.name === 'AbortError') return;
      state.results = [];
      state.searched = true;
      renderRows();
      renderErrors([{variant: '', error: 'Request failed: ' + (err && err.message ? err.message : 'network error')}]);
      metaEl.textContent = '';
    })
    .then(function(){
      if (!signal.aborted) setBusy(false);
    });
}

function grab(row, btn){
  var guid = row.guid;
  var indexerId = row.indexerId;
  if (!guid || indexerId === undefined || indexerId === null){
    toast('This result has no grab information.', 'err');
    return;
  }
  btn.disabled = true;
  fetch('?action=grab', {
    method: 'POST',
    headers: {'Content-Type': 'application/json'},
    body: JSON.stringify({guid: guid, indexerId: indexerId})
  })
    .then(function(res){ return res.json(); })
    .then(function(data){
      if (data.ok){
        btn.textContent = 'Grabbed';
        toast('Sent to download client: ' + (row.title || guid), 'ok');
      } else {
        btn.disabled = false;
        toast(data.error || 'Grab failed.', 'err');
      }
    })
    .catch(function(){
      btn.disabled = false;
      toast('Grab request failed.', 'err');
    });
}

function selectedIndexerIds(){
  var boxes = indexersListEl.querySelectorAll('input[type=checkbox][data-id]');
  var ids = [];
  for (var i = 0; i < boxes.length; i++){
    if (boxes[i].checked) ids.push(boxes[i].getAttribute('data-id'));
  }
  return ids;
}

function updateIndexersSummary(){
  var boxes = indexersListEl.querySelectorAll('input[type=checkbox][data-id]');
  var checked = 0;
  for (var i = 0; i < boxes.length; i++) if (boxes[i].checked) checked++;
  indexersSummaryEl.textContent = checked === 0 ? 'All indexers'
    : checked + ' indexer' + (checked === 1 ? '' : 's') + ' selected';
}

function loadIndexers(){
  fetch('?action=indexers')
    .then(function(res){ return res.json(); })
    .then(function(data){
      indexersListEl.innerHTML = '';
      if (!Array.isArray(data)){
        indexersListEl.appendChild(el('div', 'row', data && data.error ? data.error : 'Failed to load indexers.'));
        return;
      }
      if (!data.length){
        indexersListEl.appendChild(el('div', 'row', 'No indexers configured in Prowlarr.'));
        return;
      }
      for (var i = 0; i < data.length; i++){
        var idx = data[i];
        var row = el('div', 'row');
        var cb = el('input');
        cb.type = 'checkbox';
        cb.setAttribute('data-id', String(idx.id));
        cb.addEventListener('change', function(){ updateIndexersSummary(); });
        var lab = el('label');
        lab.style.cursor = 'pointer';
        lab.appendChild(cb);
        lab.appendChild(document.createTextNode(' ' + (idx.name || '#' + idx.id) + (idx.enable ? '' : ' (disabled)')));
        row.appendChild(lab);
        indexersListEl.appendChild(row);
      }
    })
    .catch(function(){
      indexersListEl.innerHTML = '';
      indexersListEl.appendChild(el('div', 'row', 'Failed to load indexers.'));
    });
}

function loadCategories(){
  fetch('?action=categories')
    .then(function(res){ return res.json(); })
    .then(function(data){
      if (!Array.isArray(data)) return;
      for (var i = 0; i < data.length; i++){
        var c = data[i];
        var o = el('option', null, c.name || String(c.id));
        o.value = String(c.id);
        categoryEl.appendChild(o);
        var subs = c.subCategories || [];
        for (var j = 0; j < subs.length; j++){
          var s = subs[j];
          var so = el('option', null, '  ' + (s.name || String(s.id)));
          so.value = String(s.id);
          categoryEl.appendChild(so);
        }
      }
    })
    .catch(function(){});
}

