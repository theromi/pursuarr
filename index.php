<?php
/**
 * Pursuarr — a better search interface for Prowlarr (single file, no dependencies).
 *
 * Drop this file into a web root and open it. Requires PHP 8.1+ with ext-curl.
 *
 * SECURITY: There is NO application authentication by design. Anyone who can reach
 * this app can search, grab releases and edit settings (including the Prowlarr URL
 * and API key). Protect this path — ideally the whole vhost — at your reverse proxy
 * (basic auth, VPN, tailscale, IP allowlist ...). The Prowlarr API key never reaches
 * the browser; it lives only in settings.php (chmod 0600, kept outside the docroot
 * when possible, else denied via .htaccess).
 */
declare(strict_types=1);

const PURSUARR_VERSION = '1.0.0';
const PURSUARR_MAX_GRAB_BODY = 65536;
const PURSUARR_SEARCH_TYPES = ['search', 'tvsearch', 'movie', 'music', 'book'];

function pursuarr_h(?string $s): string
{
    return htmlspecialchars((string)$s, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
}

function pursuarr_json($data, int $code = 200): void
{
    http_response_code($code);
    header('Content-Type: application/json; charset=utf-8');
    echo json_encode($data, JSON_HEX_TAG | JSON_HEX_AMP | JSON_HEX_APOS | JSON_HEX_QUOT | JSON_UNESCAPED_SLASHES);
    exit;
}

/* ---------------------------------------------------------------- config --- */

function pursuarr_default_settings(): array
{
    return [
        'prowlarr_url' => 'http://localhost:9696',
        'prowlarr_api_key' => '',
        'expansion_groups' => [
            ['x265', 'h265', 'HEVC'],
            ['x264', 'h264', 'AVC'],
        ],
        'max_search_variants' => 5,
        'default_limit' => 100,
        'search_timeout' => 90,
        'download_client_id' => null,
        'verify_tls' => true,
    ];
}

function pursuarr_settings_candidates(): array
{
    $out = [];
    $env = getenv('PURSUARR_SETTINGS');
    if (is_string($env) && trim($env) !== '') {
        $out[] = $env;
    }
    $out[] = __DIR__ . '/../settings.php';
    $out[] = __DIR__ . '/settings.php';
    return array_values(array_unique($out));
}

function pursuarr_normalize_settings(array $raw): array
{
    $d = pursuarr_default_settings();
    $s = array_merge($d, $raw);

    $url = trim((string)$s['prowlarr_url']);
    if ($url !== '' && !preg_match('#^https?://#i', $url)) {
        $url = 'http://' . $url;
    }
    $s['prowlarr_url'] = rtrim($url, '/');

    $s['prowlarr_api_key'] = trim((string)$s['prowlarr_api_key']);
    $s['max_search_variants'] = max(1, min(20, (int)$s['max_search_variants']));
    $s['default_limit'] = max(1, min(1000, (int)$s['default_limit']));
    $s['search_timeout'] = max(5, min(600, (int)$s['search_timeout']));

    $dc = trim((string)($s['download_client_id'] ?? ''));
    $s['download_client_id'] = $dc === '' ? null : (is_numeric($dc) ? (int)$dc : $dc);

    $s['verify_tls'] = (bool)$s['verify_tls'];

    $groups = [];
    foreach ((array)$s['expansion_groups'] as $group) {
        if (!is_array($group)) {
            continue;
        }
        $members = [];
        foreach ($group as $m) {
            $m = trim((string)$m);
            if ($m !== '' && !in_array($m, $members, true)) {
                $members[] = $m;
            }
        }
        if (count($members) > 0) {
            $groups[] = $members;
        }
    }
    $s['expansion_groups'] = $groups;

    return $s;
}

function pursuarr_load_settings(): ?array
{
    static $cached = false;
    static $value = null;
    if ($cached) {
        return $value;
    }
    $cached = true;
    foreach (pursuarr_settings_candidates() as $path) {
        if (is_file($path)) {
            $data = require $path;
            if (is_array($data)) {
                $value = pursuarr_normalize_settings($data);
                return $value;
            }
        }
    }
    return null;
}

function pursuarr_write_settings(array $settings): array
{
    $export = var_export($settings, true);
    $php = "<?php\n// Pursuarr settings file — generated by the app. Keep out of reach of the web.\nreturn " . $export . ";\n";
    foreach (pursuarr_settings_candidates() as $path) {
        $dir = dirname($path);
        if (!is_dir($dir) || !is_writable($dir)) {
            continue;
        }
        if (is_file($path) && !is_writable($path)) {
            continue;
        }
        if (@file_put_contents($path, $php) === false) {
            continue;
        }
        @chmod($path, 0600);
        if (function_exists('opcache_invalidate')) {
            @opcache_invalidate($path, true);
        }
        if (realpath($dir) === realpath(__DIR__)) {
            pursuarr_write_htaccess($dir);
        }
        return ['ok' => true, 'path' => $path, 'error' => null];
    }
    return [
        'ok' => false,
        'path' => '',
        'error' => 'Could not write settings.php (tried ' . implode(', ', pursuarr_settings_candidates()) . '). Check directory permissions.',
    ];
}

function pursuarr_write_htaccess(string $dir): void
{
    $path = $dir . '/.htaccess';
    $rule = "<Files settings.php>\n    Require all denied\n</Files>\n";
    if (is_file($path)) {
        $existing = (string)@file_get_contents($path);
        if (str_contains($existing, 'settings.php')) {
            return;
        }
        @file_put_contents($path, rtrim($existing) . "\n\n" . $rule);
        return;
    }
    @file_put_contents($path, $rule);
}

function pursuarr_settings_exposed_url(string $path): ?string
{
    $docroot = (string)($_SERVER['DOCUMENT_ROOT'] ?? '');
    if ($docroot === '') {
        return null;
    }
    $rp = realpath($path);
    $rd = realpath($docroot);
    if ($rp === false || $rd === false || $rp === $rd) {
        return null;
    }
    if (!str_starts_with($rp, rtrim($rd, DIRECTORY_SEPARATOR) . DIRECTORY_SEPARATOR)) {
        return null;
    }
    $rel = substr($rp, strlen(rtrim($rd, DIRECTORY_SEPARATOR)) + 1);
    $rel = str_replace(DIRECTORY_SEPARATOR, '/', $rel);
    $https = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off')
        || (($_SERVER['HTTP_X_FORWARDED_PROTO'] ?? '') === 'https');
    $scheme = $https ? 'https' : 'http';
    $host = (string)($_SERVER['HTTP_HOST'] ?? 'localhost');
    $url = $scheme . '://' . $host . '/' . str_replace(' ', '%20', $rel);

    $ch = curl_init($url);
    if ($ch === false) {
        return null;
    }
    curl_setopt_array($ch, [
        CURLOPT_RETURNTRANSFER => true,
        CURLOPT_TIMEOUT => 5,
        CURLOPT_CONNECTTIMEOUT => 3,
        CURLOPT_SSL_VERIFYPEER => false,
        CURLOPT_SSL_VERIFYHOST => 0,
    ]);
    $body = curl_exec($ch);
    $code = (int)curl_getinfo($ch, CURLINFO_RESPONSE_CODE);
    if ($code !== 200 || !is_string($body) || $body === '') {
        return null;
    }
    if (str_contains($body, '<?php') || str_contains($body, 'prowlarr_api_key') || str_contains($body, "return ")) {
        return $url;
    }
    return null;
}

/* ------------------------------------------------------------ http client --- */

function pursuarr_api_url(array $settings, string $path): string
{
    return $settings['prowlarr_url'] . '/api/v1' . $path;
}

function pursuarr_build_query(array $params): string
{
    $parts = [];
    foreach ($params as $key => $value) {
        if ($value === null || $value === '') {
            continue;
        }
        if (is_array($value)) {
            foreach ($value as $item) {
                if ($item === null || $item === '') {
                    continue;
                }
                $parts[] = rawurlencode((string)$key) . '=' . rawurlencode((string)$item);
            }
            continue;
        }
        $parts[] = rawurlencode((string)$key) . '=' . rawurlencode((string)$value);
    }
    return implode('&', $parts);
}

function pursuarr_curl_error_message(int $errno, string $error): string
{
    $host = 'Prowlarr';
    return match (true) {
        $errno === CURLE_COULDNT_CONNECT => "Can't connect to {$host} — is it running and reachable from this server?",
        $errno === CURLE_COULDNT_RESOLVE_HOST => "Can't resolve the Prowlarr host name — check the base URL in settings.",
        $errno === CURLE_COULDNT_RESOLVE_PROXY => "Can't resolve the HTTP proxy — check proxy settings.",
        $errno === CURLE_OPERATION_TIMEOUTED => "Request to Prowlarr timed out. Prowlarr may still be waiting on indexers (FlareSolverr can take 60s+).",
        $errno === CURLE_SSL_CONNECT_ERROR || $errno === CURLE_PEER_FAILED_VERIFICATION => "TLS error talking to Prowlarr — for self-signed certs disable 'verify TLS' in settings.",
        $errno === CURLE_GOT_NOTHING => "Prowlarr closed the connection without a response.",
        default => "Network error talking to Prowlarr" . ($error !== '' ? " ({$error})" : " (cURL {$errno})"),
    };
}

function pursuarr_http_error_message(int $code, string $body): string
{
    $snippet = trim(preg_replace('/\s+/', ' ', strip_tags($body)) ?? '');
    $snippet = mb_substr($snippet, 0, 200);
    $detail = '';
    $decoded = json_decode($body, true);
    if (is_array($decoded)) {
        foreach (['message', 'description', 'error', 'title'] as $k) {
            if (isset($decoded[$k]) && is_string($decoded[$k]) && $decoded[$k] !== '') {
                $detail = mb_substr(preg_replace('/\s+/', ' ', $decoded[$k]) ?? '', 0, 200);
                break;
            }
        }
    }
    if ($detail === '' && $snippet !== '') {
        $detail = $snippet;
    }
    return match (true) {
        $code === 401 => '401 Unauthorized — check the API key in settings' . ($detail !== '' ? " ({$detail})" : ''),
        $code === 403 => '403 Forbidden — the API key is not allowed to do this' . ($detail !== '' ? " ({$detail})" : ''),
        $code === 404 => '404 Not Found — check the Prowlarr base URL in settings' . ($detail !== '' ? " ({$detail})" : ''),
        default => "HTTP {$code} from Prowlarr" . ($detail !== '' ? ": {$detail}" : ''),
    };
}

function pursuarr_decode_body(string $body): array
{
    $decoded = json_decode($body, true);
    if (!is_array($decoded)) {
        $snippet = trim(preg_replace('/\s+/', ' ', strip_tags($body)) ?? '');
        $snippet = mb_substr($snippet, 0, 120);
        return ['ok' => false, 'error' => 'Invalid JSON response from Prowlarr' . ($snippet !== '' ? " (got: {$snippet})" : ''), 'json' => null];
    }
    return ['ok' => true, 'error' => null, 'json' => $decoded];
}

function pursuarr_build_curl(string $url, array $settings, ?int $timeoutSec = null, ?string $apiKey = null): \CurlHandle
{
    $key = $apiKey ?? (string)$settings['prowlarr_api_key'];
    $verify = (bool)($settings['verify_tls'] ?? true);
    $ch = curl_init($url);
    curl_setopt_array($ch, [
        CURLOPT_RETURNTRANSFER => true,
        CURLOPT_HTTPHEADER => [
            'Accept: application/json',
            'X-Api-Key: ' . $key,
        ],
        CURLOPT_CONNECTTIMEOUT => 5,
        CURLOPT_TIMEOUT => $timeoutSec ?? (int)$settings['search_timeout'],
        CURLOPT_SSL_VERIFYPEER => $verify,
        CURLOPT_SSL_VERIFYHOST => $verify ? 2 : 0,
        CURLOPT_PROTOCOLS => CURLPROTO_HTTP | CURLPROTO_HTTPS,
        CURLOPT_FOLLOWLOCATION => false,
    ]);
    return $ch;
}

function pursuarr_request_json(
    string $method,
    string $path,
    array $settings,
    ?array $query = null,
    ?array $body = null,
    ?int $timeoutSec = null
): array {
    $url = pursuarr_api_url($settings, $path);
    $qs = $query !== null ? pursuarr_build_query($query) : '';
    if ($qs !== '') {
        $url .= '?' . $qs;
    }
    $ch = pursuarr_build_curl($url, $settings, $timeoutSec);
    if (strtoupper($method) === 'POST') {
        $payload = json_encode($body ?? new stdClass(), JSON_HEX_TAG);
        curl_setopt_array($ch, [
            CURLOPT_POST => true,
            CURLOPT_POSTFIELDS => (string)$payload,
            CURLOPT_HTTPHEADER => [
                'Accept: application/json',
                'Content-Type: application/json',
                'X-Api-Key: ' . (string)$settings['prowlarr_api_key'],
            ],
        ]);
    }
    $respBody = curl_exec($ch);
    $errno = curl_errno($ch);
    $err = curl_error($ch);
    $code = (int)curl_getinfo($ch, CURLINFO_RESPONSE_CODE);

    if (!is_string($respBody)) {
        return ['ok' => false, 'error' => pursuarr_curl_error_message($errno, $err), 'json' => null, 'http_code' => $code];
    }
    if ($errno !== 0) {
        return ['ok' => false, 'error' => pursuarr_curl_error_message($errno, $err), 'json' => null, 'http_code' => $code];
    }
    if ($code >= 400) {
        return ['ok' => false, 'error' => pursuarr_http_error_message($code, $respBody), 'json' => null, 'http_code' => $code];
    }
    $decoded = pursuarr_decode_body($respBody);
    return ['ok' => $decoded['ok'], 'error' => $decoded['error'], 'json' => $decoded['json'], 'http_code' => $code];
}

function pursuarr_search_multi(array $queries, array $common, array $settings): array
{
    $timeout = (int)$settings['search_timeout'];
    $mh = curl_multi_init();
    $handles = [];
    foreach ($queries as $i => $q) {
        $params = $common;
        $params['query'] = $q;
        $url = pursuarr_api_url($settings, '/search') . '?' . pursuarr_build_query($params);
        $ch = pursuarr_build_curl($url, $settings, $timeout);
        curl_multi_add_handle($mh, $ch);
        $handles[$i] = $ch;
    }

    do {
        $status = curl_multi_exec($mh, $running);
        if ($running > 0) {
            $sel = curl_multi_select($mh, 1.0);
            if ($sel === -1) {
                usleep(20000);
            }
        }
    } while ($running > 0 && $status === CURLM_OK);

    $multiErrors = [];
    while (($info = curl_multi_info_read($mh, $queued)) !== false) {
        $result = (int)($info['result'] ?? 0);
        if ($result !== 0) {
            $multiErrors[spl_object_id($info['handle'])] = $result;
        }
    }

    $out = [];
    foreach ($handles as $i => $ch) {
        $body = curl_multi_getcontent($ch);
        $errno = $multiErrors[spl_object_id($ch)] ?? curl_errno($ch);
        $err = curl_error($ch);
        $code = (int)curl_getinfo($ch, CURLINFO_RESPONSE_CODE);
        $entry = ['query' => (string)$queries[$i], 'ok' => false, 'results' => [], 'error' => null];
        if ($errno !== 0) {
            $entry['error'] = pursuarr_curl_error_message($errno, $err);
        } elseif ($code >= 400) {
            $entry['error'] = pursuarr_http_error_message($code, is_string($body) ? $body : '');
        } else {
            $decoded = pursuarr_decode_body(is_string($body) ? $body : '');
            if (!$decoded['ok']) {
                $entry['error'] = $decoded['error'];
            } elseif (!array_is_list($decoded['json'])) {
                $entry['error'] = 'Unexpected response from Prowlarr search endpoint.';
            } else {
                $entry['ok'] = true;
                $entry['results'] = $decoded['json'];
            }
        }
        curl_multi_remove_handle($mh, $ch);
        $out[$i] = $entry;
    }
    curl_multi_close($mh);
    return $out;
}

/* ---------------------------------------------------------------- parser --- */

function pursuarr_tokenize(string $query): array
{
    $tokens = [];
    $len = strlen($query);
    $i = 0;
    while ($i < $len) {
        $c = $query[$i];
        if ($c === ' ' || $c === "\t" || $c === "\n" || $c === "\r") {
            $i++;
            continue;
        }
        $neg = false;
        if ($c === '-' && $i + 1 < $len && !ctype_space($query[$i + 1])) {
            $neg = true;
            $i++;
            $c = $query[$i];
        }
        if ($c === '"') {
            $i++;
            $start = $i;
            while ($i < $len && $query[$i] !== '"') {
                $i++;
            }
            $text = substr($query, $start, $i - $start);
            if ($i < $len) {
                $i++;
            }
            if ($text !== '') {
                $tokens[] = ['type' => $neg ? 'exact_exclude' : 'exact', 'text' => $text];
            }
            continue;
        }
        if ($c === '{') {
            $start = $i;
            while ($i < $len && $query[$i] !== '}') {
                $i++;
            }
            if ($i < $len) {
                $i++;
            }
            $text = substr($query, $start, $i - $start);
            if ($text !== '') {
                $tokens[] = ['type' => $neg ? 'exclude' : 'id', 'text' => $text];
            }
            continue;
        }
        $start = $i;
        while ($i < $len && !ctype_space($query[$i])) {
            $i++;
        }
        $text = substr($query, $start, $i - $start);
        if ($text !== '') {
            $tokens[] = ['type' => $neg ? 'exclude' : 'term', 'text' => $text];
        }
    }
    return $tokens;
}

function pursuarr_is_sent(array $token): bool
{
    return in_array($token['type'], ['term', 'exact', 'id'], true);
}

function pursuarr_base_query(array $tokens): string
{
    $parts = [];
    foreach ($tokens as $t) {
        if (pursuarr_is_sent($t)) {
            $parts[] = $t['text'];
        }
    }
    return implode(' ', $parts);
}

function pursuarr_plan_variants(array $tokens, array $groups, int $maxVariants): array
{
    $sent = [];
    foreach ($tokens as $t) {
        if (pursuarr_is_sent($t)) {
            $sent[] = $t;
        }
    }
    $altLists = [];
    foreach ($sent as $t) {
        $alts = [$t['text']];
        if ($t['type'] === 'term') {
            foreach ($groups as $group) {
                $hit = false;
                foreach ($group as $member) {
                    if (strcasecmp((string)$member, (string)$t['text']) === 0) {
                        $hit = true;
                        break;
                    }
                }
                if (!$hit) {
                    continue;
                }
                foreach ($group as $member) {
                    $member = (string)$member;
                    $dup = false;
                    foreach ($alts as $a) {
                        if (strcasecmp((string)$a, $member) === 0) {
                            $dup = true;
                            break;
                        }
                    }
                    if (!$dup) {
                        $alts[] = $member;
                    }
                }
            }
        }
        $altLists[] = $alts;
    }

    $combos = [[]];
    foreach ($altLists as $i => $alts) {
        if (count($alts) <= 1) {
            continue;
        }
        $next = [];
        foreach ($combos as $combo) {
            foreach ($alts as $a) {
                $combo2 = $combo;
                $combo2[$i] = $a;
                $next[] = $combo2;
            }
        }
        $combos = $next;
        if (count($combos) > 1024) {
            break;
        }
    }

    $variants = [];
    foreach ($combos as $combo) {
        $parts = [];
        foreach ($sent as $i => $t) {
            $parts[] = array_key_exists($i, $combo) ? $combo[$i] : $t['text'];
        }
        $q = implode(' ', $parts);
        if (!in_array($q, $variants, true)) {
            $variants[] = $q;
        }
    }
    return array_slice($variants, 0, max(1, $maxVariants));
}

function pursuarr_normalize_title_tokens(string $s): array
{
    $s = mb_strtolower($s, 'UTF-8');
    $s = (string)preg_replace('/[^\p{L}\p{N}]+/u', ' ', $s);
    $s = trim((string)preg_replace('/\s+/u', ' ', $s));
    return $s === '' ? [] : explode(' ', $s);
}

function pursuarr_contains_sequence(array $haystack, array $needle): bool
{
    $n = count($needle);
    $h = count($haystack);
    if ($n === 0) {
        return true;
    }
    if ($n > $h) {
        return false;
    }
    for ($i = 0; $i <= $h - $n; $i++) {
        $ok = true;
        for ($j = 0; $j < $n; $j++) {
            if ($haystack[$i + $j] !== $needle[$j]) {
                $ok = false;
                break;
            }
        }
        if ($ok) {
            return true;
        }
    }
    return false;
}

function pursuarr_post_filter(array $results, array $tokens): array
{
    $exclusions = [];
    $exacts = [];
    $exactExclusions = [];
    foreach ($tokens as $t) {
        if ($t['type'] === 'exclude') {
            $exclusions[] = mb_strtolower((string)$t['text'], 'UTF-8');
        } elseif ($t['type'] === 'exact') {
            $exacts[] = pursuarr_normalize_title_tokens((string)$t['text']);
        } elseif ($t['type'] === 'exact_exclude') {
            $exactExclusions[] = pursuarr_normalize_title_tokens((string)$t['text']);
        }
    }
    $out = [];
    foreach ($results as $r) {
        if (!is_array($r)) {
            continue;
        }
        $title = (string)($r['title'] ?? '');
        $titleLower = mb_strtolower($title, 'UTF-8');
        foreach ($exclusions as $e) {
            if ($e !== '' && str_contains($titleLower, $e)) {
                continue 2;
            }
        }
        $titleTokens = pursuarr_normalize_title_tokens($title);
        foreach ($exacts as $phrase) {
            if (!pursuarr_contains_sequence($titleTokens, $phrase)) {
                continue 2;
            }
        }
        foreach ($exactExclusions as $phrase) {
            if (pursuarr_contains_sequence($titleTokens, $phrase)) {
                continue 2;
            }
        }
        $out[] = $r;
    }
    return $out;
}

function pursuarr_dedupe(array $results): array
{
    $seen = [];
    $out = [];
    foreach ($results as $r) {
        if (!is_array($r)) {
            continue;
        }
        $guid = trim((string)($r['guid'] ?? ''));
        $key = $guid !== ''
            ? 'g:' . $guid
            : 'k:' . (string)($r['indexerId'] ?? '') . '|' . (string)($r['title'] ?? '') . '|' . (string)($r['size'] ?? '');
        if (isset($seen[$key])) {
            continue;
        }
        $seen[$key] = true;
        $out[] = $r;
    }
    return $out;
}

function pursuarr_list_param($value): array
{
    if ($value === null || $value === '') {
        return [];
    }
    $items = is_array($value) ? $value : explode(',', (string)$value);
    $out = [];
    foreach ($items as $item) {
        $item = trim((string)$item);
        if ($item !== '' && !in_array($item, $out, true)) {
            $out[] = $item;
        }
    }
    return $out;
}

function pursuarr_valid_type($type): string
{
    $type = strtolower(trim((string)$type));
    return in_array($type, PURSUARR_SEARCH_TYPES, true) ? $type : 'search';
}

/* ------------------------------------------------------------- settings UI --- */

function pursuarr_groups_to_text(array $groups): string
{
    $lines = [];
    foreach ($groups as $g) {
        $lines[] = implode(' | ', $g);
    }
    return implode("\n", $lines);
}

function pursuarr_parse_groups_text(string $text): array
{
    $groups = [];
    foreach (preg_split('/\R/', $text) as $line) {
        $line = trim($line);
        if ($line === '') {
            continue;
        }
        $members = [];
        foreach (explode('|', $line) as $part) {
            $part = trim($part);
            if ($part !== '' && !in_array($part, $members, true)) {
                $members[] = $part;
            }
        }
        if (count($members) > 0) {
            $groups[] = $members;
        }
    }
    return $groups;
}

function pursuarr_handle_settings_post(): void
{
    $current = pursuarr_load_settings() ?? pursuarr_default_settings();
    $verifyTls = isset($_POST['verify_tls']) && $_POST['verify_tls'] !== '' && $_POST['verify_tls'] !== '0';
    $candidate = pursuarr_normalize_settings([
        'prowlarr_url' => (string)($_POST['prowlarr_url'] ?? ''),
        'prowlarr_api_key' => (string)($_POST['prowlarr_api_key'] ?? ''),
        'expansion_groups' => pursuarr_parse_groups_text((string)($_POST['expansion_groups'] ?? '')),
        'max_search_variants' => (int)($_POST['max_search_variants'] ?? $current['max_search_variants']),
        'default_limit' => (int)($_POST['default_limit'] ?? $current['default_limit']),
        'search_timeout' => (int)($_POST['search_timeout'] ?? $current['search_timeout']),
        'download_client_id' => trim((string)($_POST['download_client_id'] ?? '')),
        'verify_tls' => $verifyTls,
    ]);

    if ($candidate['prowlarr_url'] === '' || preg_match('#^https?://$#i', $candidate['prowlarr_url'])) {
        pursuarr_render_settings($current, pursuarr_load_settings() === null, null, 'Prowlarr base URL is required.');
        return;
    }

    $test = pursuarr_request_json('GET', '/system/status', $candidate, null, null, 20);
    if (!$test['ok']) {
        pursuarr_render_settings($current, pursuarr_load_settings() === null, null, 'Connection test failed — settings not saved. ' . $test['error']);
        return;
    }

    $written = pursuarr_write_settings($candidate);
    if (!$written['ok']) {
        pursuarr_render_settings($current, pursuarr_load_settings() === null, null, $written['error']);
        return;
    }

    $notice = 'Settings saved to ' . $written['path'] . '.';
    $warn = pursuarr_settings_exposed_url($written['path']);
    if ($warn !== null) {
        $notice .= ' WARNING: settings.php is reachable over HTTP at ' . $warn . ' — move it out of the web root or deny access to it.';
    }
    pursuarr_render_settings($candidate, false, $notice, null);
}

