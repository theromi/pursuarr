function pursuarr_main(): void
{
    if (!function_exists('curl_init')) {
        pursuarr_render_fatal(
            'The PHP cURL extension is required but not loaded. Install/enable it '
            . '(e.g. <code>apt install php-curl</code>, <code>dnf install php-curl</code>, '
            . 'or uncomment <code>extension=curl</code> in php.ini) and reload this page.'
        );
    }

    $action = (string)($_GET['action'] ?? '');
    $method = strtoupper((string)($_SERVER['REQUEST_METHOD'] ?? 'GET'));
    $settings = pursuarr_load_settings();

    if ($settings === null && in_array($action, ['search', 'grab', 'indexers', 'categories'], true)) {
        pursuarr_json(['ok' => false, 'error' => 'Pursuarr is not configured yet — open the app and complete setup.'], 503);
    }

    if ($settings === null && !in_array($action, ['settings', 'status', 'parse'], true)) {
        pursuarr_render_settings(null, true, null, null);
        return;
    }

    switch ($action) {
        case '':
            pursuarr_render_app($settings ?? pursuarr_default_settings());
            return;

        case 'search':
            pursuarr_action_search($settings ?? pursuarr_default_settings());
            return;

        case 'grab':
            pursuarr_action_grab($settings ?? pursuarr_default_settings());
            return;

        case 'indexers':
            pursuarr_action_indexers($settings ?? pursuarr_default_settings());
            return;

        case 'categories':
            pursuarr_action_categories($settings ?? pursuarr_default_settings());
            return;

        case 'status':
            pursuarr_action_status($settings ?? pursuarr_default_settings());
            return;

        case 'parse':
            pursuarr_action_parse($settings ?? pursuarr_default_settings());
            return;

        case 'settings':
            if ($method === 'POST') {
                pursuarr_handle_settings_post();
                return;
            }
            pursuarr_render_settings($settings, $settings === null, $_GET['saved'] ?? null, null);
            return;

        default:
            pursuarr_render_app($settings ?? pursuarr_default_settings());
            return;
    }
}

function pursuarr_action_search(array $settings): void
{
    @set_time_limit(300);

    $query = (string)($_GET['query'] ?? '');
    $type = pursuarr_valid_type($_GET['type'] ?? 'search');
    $limit = (int)($_GET['limit'] ?? $settings['default_limit']);
    if ($limit <= 0) {
        $limit = (int)$settings['default_limit'];
    }
    $limit = max(1, min(1000, $limit));

    $indexerIds = pursuarr_list_param($_GET['indexerIds'] ?? null);
    $categories = pursuarr_list_param($_GET['categories'] ?? null);

    $tokens = pursuarr_tokenize($query);
    $variants = pursuarr_plan_variants($tokens, $settings['expansion_groups'], (int)$settings['max_search_variants']);

    if ($variants === [] || $variants[0] === '') {
        pursuarr_json([
            'results' => [],
            'variantsUsed' => [],
            'errors' => [['variant' => '', 'error' => 'Query contains no searchable terms (only exclusions). Add at least one term to search.']],
        ]);
        return;
    }

    $common = ['type' => $type, 'limit' => $limit];
    if ($indexerIds !== []) {
        $common['indexerIds'] = $indexerIds;
    }
    if ($categories !== []) {
        $common['categories'] = $categories;
    }

    $perVariant = pursuarr_search_multi($variants, $common, $settings);

    $results = [];
    $errors = [];
    $used = [];
    foreach ($perVariant as $entry) {
        $used[] = $entry['query'];
        if (!$entry['ok']) {
            $errors[] = ['variant' => $entry['query'], 'error' => $entry['error']];
            continue;
        }
        foreach ($entry['results'] as $r) {
            if (is_array($r)) {
                $results[] = $r;
            }
        }
    }

    $results = pursuarr_post_filter(pursuarr_dedupe($results), $tokens);

    pursuarr_json([
        'results' => $results,
        'variantsUsed' => $used,
        'errors' => $errors,
    ]);
}

function pursuarr_action_grab(array $settings): void
{
    if (strtoupper((string)($_SERVER['REQUEST_METHOD'] ?? 'GET')) !== 'POST') {
        pursuarr_json(['ok' => false, 'error' => 'Use POST with a JSON body {guid, indexerId}.'], 405);
    }

    $raw = (string)file_get_contents('php://input');
    if (strlen($raw) > PURSUARR_MAX_GRAB_BODY) {
        pursuarr_json(['ok' => false, 'error' => 'Request body too large — send only {guid, indexerId}.'], 413);
    }

    $body = json_decode($raw, true);
    if (!is_array($body)) {
        pursuarr_json(['ok' => false, 'error' => 'Invalid JSON body — expected {guid, indexerId}.'], 400);
    }

    $guid = trim((string)($body['guid'] ?? ''));
    $indexerId = $body['indexerId'] ?? null;
    if ($guid === '') {
        pursuarr_json(['ok' => false, 'error' => 'Missing "guid" — search first, then grab from a result.'], 400);
    }
    if ($indexerId === null || $indexerId === '' || !is_numeric($indexerId)) {
        pursuarr_json(['ok' => false, 'error' => 'Missing or invalid "indexerId".'], 400);
    }

    $payload = ['guid' => $guid, 'indexerId' => (int)$indexerId];
    if ($settings['download_client_id'] !== null) {
        $payload['downloadClientId'] = $settings['download_client_id'];
    }

    $res = pursuarr_request_json('POST', '/search', $settings, null, $payload);
    if (!$res['ok']) {
        if ($res['http_code'] === 404) {
            pursuarr_json(['ok' => false, 'error' => "Release expired in Prowlarr's cache — search again."]);
        }
        pursuarr_json(['ok' => false, 'error' => (string)$res['error']]);
    }
    pursuarr_json(['ok' => true, 'response' => $res['json']]);
}

function pursuarr_action_indexers(array $settings): void
{
    $res = pursuarr_request_json('GET', '/indexer', $settings, null, null, 20);
    if (!$res['ok'] || !is_array($res['json'])) {
        pursuarr_json(['ok' => false, 'error' => (string)$res['error']], 502);
    }
    $out = [];
    foreach ($res['json'] as $item) {
        if (!is_array($item)) {
            continue;
        }
        $out[] = [
            'id' => $item['id'] ?? null,
            'name' => (string)($item['name'] ?? ''),
            'protocol' => (string)($item['protocol'] ?? ''),
            'enable' => (bool)($item['enable'] ?? true),
        ];
    }
    pursuarr_json($out);
}

function pursuarr_action_categories(array $settings): void
{
    $res = pursuarr_request_json('GET', '/categories', $settings, null, null, 20);
    if (!$res['ok'] || !is_array($res['json'])) {
        pursuarr_json([]);
    }
    $out = [];
    foreach ($res['json'] as $item) {
        if (!is_array($item)) {
            continue;
        }
        $subs = [];
        foreach ((array)($item['subCategories'] ?? []) as $sub) {
            if (is_array($sub)) {
                $subs[] = ['id' => $sub['id'] ?? null, 'name' => (string)($sub['name'] ?? '')];
            }
        }
        $out[] = [
            'id' => $item['id'] ?? null,
            'name' => (string)($item['name'] ?? ''),
            'subCategories' => $subs,
        ];
    }
    pursuarr_json($out);
}

function pursuarr_action_status(array $settings): void
{
    $url = $_GET['url'] ?? $_POST['url'] ?? null;
    $key = $_GET['key'] ?? $_POST['key'] ?? null;
    $verifyTls = $_GET['verify_tls'] ?? $_POST['verify_tls'] ?? null;

    if ($url !== null || $key !== null) {
        $settings = pursuarr_normalize_settings([
            'prowlarr_url' => (string)($url ?? $settings['prowlarr_url']),
            'prowlarr_api_key' => (string)($key ?? $settings['prowlarr_api_key']),
            'verify_tls' => $verifyTls === null ? $settings['verify_tls'] : !in_array((string)$verifyTls, ['0', 'false', 'off'], true),
        ]);
    }

    $res = pursuarr_request_json('GET', '/system/status', $settings, null, null, 20);
    if (!$res['ok']) {
        pursuarr_json(['ok' => false, 'error' => (string)$res['error'], 'url' => $settings['prowlarr_url']]);
    }
    $json = is_array($res['json']) ? $res['json'] : [];
    pursuarr_json([
        'ok' => true,
        'url' => $settings['prowlarr_url'],
        'version' => (string)($json['version'] ?? ''),
        'instanceName' => (string)($json['instanceName'] ?? ''),
    ]);
}

function pursuarr_action_parse(array $settings): void
{
    $query = (string)($_GET['query'] ?? '');
    $tokens = pursuarr_tokenize($query);
    $variants = pursuarr_plan_variants(
        $tokens,
        $settings['expansion_groups'],
        (int)$settings['max_search_variants']
    );
    $classified = [];
    foreach ($tokens as $t) {
        $classified[] = ['type' => $t['type'], 'text' => $t['text'], 'sent' => pursuarr_is_sent($t)];
    }
    pursuarr_json([
        'query' => $query,
        'tokens' => $classified,
        'prowlarrQuery' => pursuarr_base_query($tokens),
        'variants' => $variants,
    ]);
}

